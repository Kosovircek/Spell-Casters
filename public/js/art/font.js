const glyphCache = {};
export function glyph(ch, color) {
  const key = ch + color;
  if (glyphCache[key]) return glyphCache[key];
  const rows = FONT[ch]; const c = makeCanvas(7, 9); const g = c.getContext('2d');
  if (rows) {
    g.fillStyle = '#0b0910';
    for (let y = 0; y < 7; y++) for (let x = 0; x < 5; x++) if (rows[y][x] === '#')
      for (const [ox, oy] of [[-1, 0], [1, 0], [0, -1], [0, 1], [1, 1]]) g.fillRect(x + 1 + ox, y + 1 + oy, 1, 1);
    g.fillStyle = color;
    for (let y = 0; y < 7; y++) for (let x = 0; x < 5; x++) if (rows[y][x] === '#') g.fillRect(x + 1, y + 1, 1, 1);
  }
  return (glyphCache[key] = c);
}
// Draws a word centered at (cx, y); colorFn(i) picks each letter's color.
export function drawWord(ctx, word, cx, y, colorFn) {
  const w = word.length * 6 + 1; let x = Math.round(cx - w / 2);
  for (let i = 0; i < word.length; i++) { ctx.drawImage(glyph(word[i], colorFn(i)), x, Math.round(y)); x += 6; }
}

