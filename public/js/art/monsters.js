const cache = {};
/**
 * Sprite for an enemy kind. flash = hit flash (white except the `keep` colours); frame = walk-cycle frame;
 * variant = extra key (the Hydra's heads still up, as a bitmask).
 */
export function monsterSprite(type, flash, frame = 0, variant = 0) {
  const m = MONSTERS[type];
  if (!m) return null;
  const key = type + (flash ? 'f' : '') + frame + '/' + variant;
  if (cache[key]) return cache[key];
  let rows = m.rows.slice();
  if (m.feet) rows.push(m.feet[frame] || m.feet[0]);
  if (m.heads) { // cut heads leave no head: blank their pixels
    m.heads.forEach((h, i) => {
      if (variant & (1 << i)) return;
      for (let y = 0; y < m.headRows; y++) rows[y] = rows[y].split('').map((c, x) => (x >= h.x0 && x <= h.x1 ? '.' : c)).join('');
    });
  }
  const w = Math.max(...rows.map(r => r.length));
  rows = rows.map(r => r.padEnd(w, '.'));
  const pal = { K, B: BONE };
  for (const [c, col] of Object.entries(m.pal)) pal[c] = flash && !(m.keep || '').includes(c) ? '#ffffff' : col;
  if (m.feet) for (const r of m.feet) for (const c of r) if (c !== '.' && !pal[c]) pal[c] = K;
  return (cache[key] = sprite(rows, pal));
}
